"""Turn a release_bench output directory into report.md.

The report lists the environment, the workload, the timing boundary, a results table per
workload size, speedups against each baseline, and checks. It states measurements only;
interpreting them is the job of your case study. Standard library only.

usage: lab12_report.py OUTPUT_DIR
"""
import csv
import json
import sys
from pathlib import Path

VARIANT_ORDER = ["cpu", "cpu-parallel", "cuda-baseline", "cuda"]
BASELINES = [("cpu-parallel", "multicore CPU"), ("cpu", "single-thread CPU"),
             ("cuda-baseline", "straightforward CUDA (Lab 07)")]


def number(text, digits=4):
    if text in ("", None):
        return "—"
    return f"{float(text):.{digits}g}"


def main():
    if len(sys.argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    directory = Path(sys.argv[1])
    environment = json.loads((directory / "environment.json").read_text(encoding="utf-8"))
    with open(directory / "summary.csv", newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise SystemExit(f"{directory / 'summary.csv'} has no rows.")

    gpu = environment.get("gpu") or {}
    detector = environment.get("detector", {})
    lines = [
        "# Release measurements",
        "",
        "Generated by `scripts/lab12_report.py` from `summary.csv` and `environment.json`. "
        "These are measurements; the case study interprets them.",
        "",
        "## Environment",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| GPU | {gpu.get('name', 'not used')} (compute capability {gpu.get('compute_capability', '—')}, "
        f"{number(gpu.get('memory_gib'), 3)} GiB) |",
        f"| CUDA runtime / driver | {gpu.get('cuda_runtime_version', '—')} / {gpu.get('cuda_driver_version', '—')} |",
        f"| Build | nvcc {environment['build']['nvcc']}, {environment['build']['host_compiler']} |",
        f"| CPU | {environment['cpu_model']}; {environment['cpu_threads']} threads used for cpu-parallel, "
        f"{environment['hardware_threads']} hardware threads |",
        f"| Host / Slurm job | {environment['host']} / {environment['slurm_job_id'] or '—'} "
        f"({environment['slurm_partition'] or '—'}) |",
        f"| Source commit | `{environment['source_commit']}` |",
        f"| Created (UTC) | {environment['created_utc']} |",
        "",
        "## Workload",
        "",
        f"- Image list `{environment['list']}`, split `{environment['split']}`: {environment['images']} images, "
        f"shapes {', '.join(environment['image_shapes'])}.",
        f"- Detector: lo {detector.get('lo')}, hi {detector.get('hi')}, radius {detector.get('radius')}, "
        f"pixel threshold {detector.get('pixel_threshold')}, block {detector.get('block')}; "
        f"configuration file `{environment['config_file'] or 'none'}`.",
        f"- {environment['repeats']} timed repetitions after {environment['warmups']} warm-up(s) per variant and size. "
        f"Decoding averaged {number(environment['decode_ms_per_image'])} ms per image.",
        "",
        "## Timing boundary",
        "",
        environment["timing_boundary"],
        "",
        "## Results",
    ]
    sizes = sorted({int(row["images"]) for row in rows})
    by_key = {(row["variant"], int(row["images"])): row for row in rows}
    present = [variant for variant in VARIANT_ORDER if any(row["variant"] == variant for row in rows)]
    for size in sizes:
        lines += ["", f"### {size} image(s) per run", "",
                  "| Variant | Threads | Median ms | IQR ms | Min–max ms | Images/s | Device compute ms | Correct |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for variant in present:
            row = by_key.get((variant, size))
            if row is None:
                continue
            lines.append(f"| {variant} | {row['threads']} | {number(row['median_ms'])} | "
                         f"{number(row['q1_ms'])}–{number(row['q3_ms'])} | {number(row['min_ms'])}–{number(row['max_ms'])} | "
                         f"{number(row['images_per_s'])} | {number(row['device_compute_median_ms'])} | {row['correct']} |")

    lines += ["", "## Speedup of `cuda` (ratio of median processing times, same boundary)", "",
              "| Images | " + " | ".join(f"vs {label}" for _, label in BASELINES) + " |",
              "| --- |" + " --- |" * len(BASELINES)]
    for size in sizes:
        final = by_key.get(("cuda", size))
        cells = []
        for baseline, _ in BASELINES:
            other = by_key.get((baseline, size))
            if final is None or other is None or float(final["median_ms"]) <= 0:
                cells.append("—")
            elif final["correct"] != "true" or other["correct"] != "true":
                cells.append("invalid (incorrect result)")
            else:
                cells.append(f"{float(other['median_ms']) / float(final['median_ms']):.3g}×")
        lines.append(f"| {size} | " + " | ".join(cells) + " |")

    checks = []
    wrong = [f"{row['variant']} ({row['images']} images)" for row in rows if row["correct"] != "true"]
    if wrong:
        checks.append("Incorrect results, so no timing claim is valid: " + ", ".join(wrong) + ".")
    if "cpu-parallel" not in present:
        checks.append("No multicore CPU baseline was measured; a speedup against one CPU thread overstates the GPU.")
    if int(environment["repeats"]) < 5:
        checks.append(f"Only {environment['repeats']} repetition(s) per configuration; variability is poorly estimated.")
    if environment["source_commit"] == "unknown":
        checks.append("The source commit is unknown; set SOURCE_COMMIT (make bench-lab12 does) so readers can rebuild.")
    if 1 in sizes:
        checks.append("Rows with 1 image describe a single-item workload; do not quote their images/s as sustained throughput.")
    lines += ["", "## Checks", ""]
    lines += [f"- {check}" for check in checks] or ["- No problems detected."]

    report = directory / "report.md"
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
